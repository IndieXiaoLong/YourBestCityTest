// 题目数量分档
export const QUESTION_COUNTS = { basic: 25, pro: 60, full: 100 } as const
export type QuizVersion = keyof typeof QUESTION_COUNTS

// 均匀抽样：保证任一版本都均衡覆盖各主题
export function pickQuestions(version: QuizVersion): Question[] {
  const total = QUESTION_COUNTS[version]
  if (total >= QUESTIONS.length) return QUESTIONS.slice()
  const step = QUESTIONS.length / total
  const picked: Question[] = []
  for (let i = 0; i < total; i++) {
    picked.push(QUESTIONS[Math.floor(i * step)])
  }
  return picked
}
