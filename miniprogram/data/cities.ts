import { DimKey, DIM_ORDER } from './dimensions'

export interface City {
  name: string
  tier: '一线' | '新一线' | '二线'
  scores: Record<DimKey, number>
  cover: string
  tags: string[]
}

const COVER_BASE = 'https://zzz-pet.oss-cn-hangzhou.aliyuncs.com/image/your_city/'

type Row = [string, '一线' | '新一线' | '二线', number[], string[]]

function build(rows: Row[]): City[] {
  return rows.map(([name, tier, arr, tags]) => {
    const scores = {} as Record<DimKey, number>
    DIM_ORDER.forEach((k, i) => { scores[k] = arr[i] })
    return { name, tier, scores, cover: COVER_BASE + encodeURIComponent(name) + '.jpg', tags }
  })
}

